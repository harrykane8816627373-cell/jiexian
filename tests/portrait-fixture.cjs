// Rotate the portrait screenshots back into board coordinates. Centers and radii are approximate.
function draft(top, right, bottom, nodes, links, circles, fixed = []) {
  const scale = (bottom - top) / 852;
  const world = ([x, y]) => [24 + (y - top) / scale, 24 + (right - x) / scale];
  const points = nodes.map(world).map(([x, y]) => [
    Math.max(42, Math.min(858, x)), Math.max(42, Math.min(498, y)),
  ]);
  const edges = links.map(([a, b]) => [Math.min(a, b) - 1, Math.max(a, b) - 1]);
  const obstacles = circles.map(([x, y, r]) => ({ center: world([x, y]), r: Math.min(96, r / scale) }));
  return { points, edges, obstacles, fixed };
}

